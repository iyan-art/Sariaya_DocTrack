# Excludes visually-ambiguous characters (0/O, 1/I/L) so a citizen reading a
# tracking number off a slip or a phone call doesn't misread it.
_TRACKING_SUFFIX_ALPHABET = "23456789ABCDEFGHJKMNPQRSTUVWXYZ"


class Office(models.Model):
    """
    The municipal office catalog — the single source of truth for what
    offices exist. WorkflowStep and DocumentLog both point here so that
    renaming an office or moving its location updates every workflow step
    and history entry that references it, instead of being baked into
    free-text strings scattered across the database.
    """
    name = models.CharField(max_length=150, unique=True)
    code = models.CharField(
        max_length=20, unique=True,
        help_text="Short code, e.g. 'TREAS'. Must match a staff member's User.office string for "
                   "release/receive permission checks and document-log attribution to resolve correctly.",
    )
    location = models.CharField(max_length=255, blank=True, help_text="Building / room, e.g. 'Municipal Hall, Room 204'")
    # Separate from `location` (which mixes building/room text) so the
    # public tracking page can show a clean "Floor: 2nd Floor" line without
    # parsing free text — admin-configurable via Office Manager.
    floor = models.CharField(max_length=50, blank=True, help_text="e.g. '2nd Floor' — shown to citizens on the public tracking page.")
    contact_person = models.CharField(max_length=150, blank=True, help_text="Department head or point of contact")
    # Optional, shown to citizens in the "ready for pickup" release email
    # (see notifications.py::send_ready_for_release_email()) when set — left
    # out of that email entirely otherwise, never fabricated.
    office_hours = models.CharField(
        max_length=150, blank=True,
        help_text="e.g. 'Mon–Fri, 8:00 AM – 5:00 PM' — shown to citizens in the release notification email.",
    )
    is_active = models.BooleanField(default=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['name']

    def __str__(self):
        return f"{self.code} — {self.name}"


class DocumentType(models.Model):
    """
    Defines a document type and its processing route across offices.
    `route` is the flat, ordered office list the release/receive/return
    engine in services.py actually runs on (Document.route_position indexes
    into it) — it is NOT hand-edited. It's regenerated by sync_route_from_steps()
    whenever an admin saves a WorkflowStep list in the Workflow Builder, so the
    two stay in lockstep without the execution engine needing to know steps exist.
    """
    class Scope(models.TextChoices):
        INTERNAL = 'internal', 'Internal'
        EXTERNAL = 'external', 'External'

    # NOT globally unique — unique together with `scope` instead (see Meta
    # below). This is what lets the same real-world document name exist as
    # two distinct rows under different purposes — e.g. "Mayor's Permit" as
    # both an EXTERNAL type (citizens can request it) and an INTERNAL one
    # (staff-only, e.g. an internal authorization), each with its own
    # workflow route/SLA configured independently in the Workflow Builder.
    name = models.CharField(max_length=150)
    description = models.TextField(blank=True)
    scope = models.CharField(
        max_length=10, choices=Scope.choices, default=Scope.EXTERNAL, db_index=True,
        help_text='EXTERNAL: citizen-facing (permits, certificates). INTERNAL: staff-only (payroll, vouchers, purchase requests). '
                   'Doubles as "Document Purpose" on the staff New Document Request form — see DocumentTypeListCreateView.',
    )
    route = models.JSONField(
        default=list, blank=True,
        help_text='Auto-generated from this type\'s WorkflowStep rows, ordered by step_number. Do not edit directly.',
    )
    daily_limit = models.PositiveIntegerField(
        null=True, blank=True,
        help_text='Maximum new requests accepted for this type per day, to manage office workload. Leave blank for no limit.',
    )
    # The per-type request-form schema: a list of
    # {key, label, type, required, placeholder?, options?, help_text?}
    # dicts, `type` one of text/textarea/number/date/tel/select. Read by
    # DocumentRequestFields.jsx on the frontend to render the right fields
    # for whichever document type was selected, and enforced server-side by
    # CreateDocumentSerializer.validate(). An empty list means "no schema
    # configured yet" — the frontend falls back to a generic field set
    # rather than showing nothing.
    request_fields = models.JSONField(default=list, blank=True)
    # The actual official file for this document type (a flat, non-fillable
    # PDF — Birth/Marriage/Death Certificate application forms, Business/
    # Building Permit forms). Every Document of this type shares the same
    # file, since there's no per-citizen field data to merge into it.
    # Served by DocumentOfficialFileView / PublicDocumentOfficialFileView,
    # gated to a document's owner or guest only once that document is
    # Released. Blank means "no file uploaded yet" for this type.
    template_file = models.FileField(upload_to='document_templates/', blank=True, null=True)
    is_active = models.BooleanField(default=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        constraints = [
            models.UniqueConstraint(fields=['name', 'scope'], name='unique_document_type_name_per_scope'),
        ]

    def sync_route_from_steps(self):
        """Rebuilds `route` from the current WorkflowStep rows and saves it."""
        self.route = list(self.steps.order_by('step_number').values_list('office__code', flat=True))
        self.save(update_fields=['route'])

    def __str__(self):
        return f"{self.name} ({self.get_scope_display()})"


class WorkflowStep(models.Model):
    """
    One sequential step in a DocumentType's processing route — the
    admin-authored definition behind the Workflow Builder UI. This is the
    layer admins actually edit; DocumentType.route (what services.py runs on)
    is a derived cache of these rows, kept in sync by sync_route_from_steps().
    """
    document_type = models.ForeignKey(DocumentType, on_delete=models.CASCADE, related_name='steps')
    step_number = models.PositiveIntegerField()
    office = models.ForeignKey(Office, on_delete=models.PROTECT, related_name='workflow_steps')
    action_required = models.CharField(
        max_length=255, blank=True,
        help_text="What happens at this step, e.g. 'Tax Assessment' or 'Administrator Approval'",
    )
    max_hours_allowed = models.PositiveIntegerField(help_text='SLA for this step, in hours (e.g. 48 for 2 days)')

    class Meta:
        ordering = ['step_number']
        constraints = [
            models.UniqueConstraint(fields=['document_type', 'step_number'], name='unique_step_number_per_document_type'),
        ]

    def __str__(self):
        return f"{self.document_type.name} — Step {self.step_number}: {self.office.code}"


class Document(models.Model):
    class Status(models.TextChoices):
        IN_PROGRESS = 'in_progress', 'In Progress'
        IN_TRANSIT = 'in_transit', 'In Transit'
        COMPLETED = 'completed', 'Completed'
        RELEASED = 'released', 'Released to Citizen'
        MISSING = 'missing', 'Missing'

    class ProcessingStage(models.TextChoices):
        """
        A second, citizen-facing status axis — independent of `status`
        above. `status` drives the physical release/receive/return engine
        (services.py) and the SLA/dwell-time/heatmap KPIs; ProcessingStage
        is a narrative, staff-authored (or auto-advanced, see services.py's
        advance_processing_stage()) sequence of stages shown as the
        Shopee-style tracking stepper on the public Track page. The two
        never have to match 1:1 — e.g. "Under Review"/"For Approval" have
        no equivalent office-transfer event at all.
        """
        SUBMITTED = 'submitted', 'Request Submitted'
        UNDER_REVIEW = 'under_review', 'Under Review'
        VERIFICATION = 'verification', 'Information Verification'
        FORM_PROCESSING = 'form_processing', 'Form Processing'
        FOR_APPROVAL = 'for_approval', 'For Approval'
        APPROVED = 'approved', 'Approved'
        DOCUMENT_GENERATED = 'document_generated', 'Document Generated'
        SOFT_COPY_AVAILABLE = 'soft_copy_available', 'Soft Copy Available'
        READY_FOR_RELEASE = 'ready_for_release', 'Ready for Release'
        COMPLETED = 'completed', 'Completed'
        REJECTED = 'rejected', 'Rejected'

    document_type = models.ForeignKey(DocumentType, on_delete=models.PROTECT, related_name='documents')
    tracking_number = models.CharField(max_length=25, unique=True, editable=False)
    origin_office = models.CharField(max_length=150, blank=True)

    form_data = models.JSONField(default=dict, blank=True)

    requested_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.SET_NULL,
        null=True, blank=True, related_name='requested_documents',
    )
    # Staff-entered name + contact email for a walk-in citizen with no
    # account (requested_by is None) — required together at request-creation
    # time (see CreateDocumentSerializer.validate()) so an automated email's
    # greeting always has a real name ("Dear Juan Dela Cruz,") instead of
    # falling back to "N/A". Both ignored whenever requested_by IS set: a
    # registered citizen's own account name/email are always used instead,
    # see notifications.py::_resolve_citizen_recipient()/
    # _requester_display_name(). Never surfaced on any public/guest-facing
    # serializer — only staff who create/manage the request can see them.
    guest_name = models.CharField(max_length=150, blank=True)
    guest_email = models.EmailField(blank=True)

    route_position = models.PositiveIntegerField(default=0)
    status = models.CharField(max_length=20, choices=Status.choices, default=Status.IN_PROGRESS, db_index=True)
    # True while an IN_TRANSIT document is being sent BACKWARD to the
    # previous office in its route (a Controlled Return, see
    # services.py::return_document()) rather than forward to the next one.
    # receive_document() branches on this to decrement route_position
    # instead of advancing it. Always False for the ordinary forward
    # release/receive flow — this never changes existing behavior.
    is_returning = models.BooleanField(default=False)
    processing_stage = models.CharField(
        max_length=30, choices=ProcessingStage.choices, default=ProcessingStage.SUBMITTED, db_index=True,
    )

    # Stored (not just derived) so it can be filtered/indexed directly —
    # e.g. for the real-time heatmap and per-office document counts.
    # Kept in sync with route_position/document_type.route on every save().
    current_office = models.CharField(max_length=150, blank=True, default='', db_index=True)

    current_handler = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.SET_NULL,
        null=True, blank=True, related_name='handled_documents',
    )

    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)
    entered_current_office_at = models.DateTimeField(auto_now_add=True)

    qr_code = models.ImageField(upload_to='document_qr/', blank=True, null=True)

    class Meta:
        indexes = [
            models.Index(fields=['status', 'current_office']),
        ]

    def save(self, *args, **kwargs):
        if not self.tracking_number:
            self.tracking_number = self._generate_tracking_number()
        self.current_office = self._resolve_current_office()
        super().save(*args, **kwargs)

    @classmethod
    def _generate_tracking_number(cls):
        """
        DOC-YYYY-SRY-NNNN-XXXX — sequential per calendar year (SRY = Sariaya)
        for phone/receipt readability, PLUS a 4-character random suffix
        (drawn from `_TRACKING_SUFFIX_ALPHABET` via `secrets`, not `random`)
        so a tracking number can't just be enumerated by counting up from
        DOC-2026-SRY-0001 — the public tracking page and QR scan resolve a
        bare tracking number with no other secret involved, so the number
        itself has to carry the unpredictability.

        The sequence is computed from the highest existing number for that
        year rather than a row count, so a deleted document never causes a
        collision. Parsed in Python (not via a DB string sort) because the
        random suffix would otherwise corrupt a plain lexicographic sort.
        Mirrors User._generate_employee_id()'s scheme.
        """
        prefix = f"DOC-{timezone.now().year}-SRY-"
        next_seq = 1
        for tracking_number in cls.objects.filter(tracking_number__startswith=prefix).values_list('tracking_number', flat=True):
            seq_part = tracking_number[len(prefix):].split('-', 1)[0]
            if seq_part.isdigit():
                next_seq = max(next_seq, int(seq_part) + 1)
        suffix = ''.join(secrets.choice(_TRACKING_SUFFIX_ALPHABET) for _ in range(4))
        return f"{prefix}{next_seq:04d}-{suffix}"

    def _resolve_current_office(self):
        route = self.document_type.route
        if self.route_position < len(route):
            return route[self.route_position]
        return route[-1]

    @property
    def is_final_step(self):
        """True if the document's current position is the LAST step in its route."""
        return self.route_position == len(self.document_type.route) - 1

    @property
    def current_step_number(self):
        """1-indexed step number, matching WorkflowStep.step_number for this document_type."""
        return self.route_position + 1

    def __str__(self):
        return f"{self.tracking_number} — {self.document_type.name} ({self.status})"


class RequestStatusHistory(models.Model):
    """
    One entry per ProcessingStage change — the source of the Shopee-style
    tracking stepper shown on the public Track page (see
    services.py::advance_processing_stage(), which is the only place these
    rows get created). Deliberately separate from DocumentLog: that model is
    an audit trail of physical office hand-offs (who scanned what, how long
    it sat where); this one is a narrative of processing progress that can
    advance with no office transfer involved at all (e.g. "Under Review").
    """
    document = models.ForeignKey(Document, on_delete=models.CASCADE, related_name='stage_history')
    stage = models.CharField(max_length=30, choices=Document.ProcessingStage.choices)
    note = models.TextField(blank=True)
    changed_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.SET_NULL,
        null=True, blank=True, related_name='stage_updates',
    )
    timestamp = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['timestamp']

    def __str__(self):
        return f"{self.document.tracking_number} — {self.stage} @ {self.timestamp:%Y-%m-%d %H:%M}"


class DocumentLog(models.Model):
    class Action(models.TextChoices):
        CREATED = 'created', 'Created'
        RELEASED = 'released', 'Released'  # sending office scans out, toward the next office in the route
        RECEIVED = 'received', 'Received'  # receiving office scans in, mid-route
        RETURNED = 'returned', 'Returned'  # receiving office scans in on the FINAL leg — back at the origin office
        RELEASED_TO_CITIZEN = 'released_to_citizen', 'Released to Citizen'
        FLAGGED_MISSING = 'flagged_missing', 'Flagged Missing'
        # Controlled Return to a previous office (services.py::return_document()
        # / receive_document()'s is_returning branch) — distinct from RETURNED
        # above, which means "finished its forward circuit," not "sent backward
        # mid-route due to an issue."
        RETURN_INITIATED = 'return_initiated', 'Returned to Previous Office'
        RETURN_RECEIVED = 'return_received', 'Return Received'
        # A citizen sending a RELEASED (terminal) document back to the office
        # that released it, because of a problem — see
        # services.py::citizen_return_document(). Distinct from the two
        # above, which are staff-initiated mid-workflow (route_position
        # still moving); this one reopens a document that had already
        # reached its terminal state.
        CITIZEN_RETURN_INITIATED = 'citizen_return_initiated', 'Returned by Citizen'
        # A citizen flagging their own delayed document for staff attention
        # (services.py::expedite_document()) — purely informational, never
        # changes status/route_position, just raises a Notification at the
        # office currently holding it.
        EXPEDITE_REQUESTED = 'expedite_requested', 'Expedite Requested'

    document = models.ForeignKey(Document, on_delete=models.CASCADE, related_name='logs')
    action = models.CharField(max_length=30, choices=Action.choices, db_index=True)
    # SET_NULL + nullable: resolved best-effort from a string (see
    # services.py::resolve_office) at log-creation time, since the acting
    # user's/document's office is still a free-text string elsewhere in the
    # system (User.office, Document.current_office) — this never blocks a
    # scan even if that string doesn't match a catalog Office.
    office = models.ForeignKey(
        Office, on_delete=models.SET_NULL, null=True, blank=True, related_name='document_logs',
    )

    # Who handed the document off (blank for the very first CREATED log,
    # where there is no prior holder).
    sender = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.SET_NULL,
        null=True, blank=True, related_name='sent_document_logs',
    )
    # Who received/performed the action.
    acted_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.SET_NULL,
        null=True, related_name='document_actions',
    )
    qr_verified = models.BooleanField(default=False)

    notes = models.TextField(blank=True)
    timestamp = models.DateTimeField(auto_now_add=True, db_index=True)
    duration_at_office = models.DurationField(null=True, blank=True)

    class Meta:
        ordering = ['timestamp']
        indexes = [
            models.Index(fields=['document', 'timestamp']),
        ]

    def __str__(self):
        return f"{self.document.tracking_number} — {self.action} @ {self.office}"


